        // ============================================================
        // CORE UPDATE
        // ============================================================
        private async Task UpdateInternal(Guid flowId, string definition)
        {
            var getUrl = $"{_orgUrl}/api/data/v9.2/workflows({flowId})?$select=statecode";

            var getRes = await _httpClient.GetAsync(getUrl);
            var getBody = await getRes.Content.ReadAsStringAsync();

            if (!getRes.IsSuccessStatusCode)
                throw new Exception(getBody);

            var statecode = JsonNode.Parse(getBody)?["statecode"]?.GetValue<int>() ?? 0;
            bool wasActive = (statecode == 1);

            // Deactivate
            if (wasActive)
            {
                await SendPatch(flowId, new JsonObject
                {
                    ["statecode"] = 0,
                    ["statuscode"] = 1
                });
            }

            // Update definition
            await SendPatch(flowId, new JsonObject
            {
                ["definition"] = definition
            });

            // Activate
            if (wasActive)
            {
                await ActivateWorkflowAsync(flowId);
            }
        }

        // ============================================================
        // 🔥 WISPR → PAD CONVERTER (FIXED)
        // ============================================================
        private string ConvertWisprToPad(string script)
        {
            var lines = script
                .Split('\n')
                .Select(l => l.Trim())
                .Where(l => !string.IsNullOrWhiteSpace(l))
                .ToList();

            var sb = new StringBuilder();

            // Header
            sb.AppendLine("@@ConnectionString: ''");
            sb.AppendLine("@@Type: 'Local'");
            sb.AppendLine("@@DesktopType: 'local'");
            sb.AppendLine("@@DisplayName: 'Local computer'");
            sb.AppendLine("IMPORT 'controlRepo.appmask' AS appmask");
            sb.AppendLine("IMPORT 'imageRepo.imgrepo' AS imgrepo");
            sb.AppendLine("@SENSITIVE: []");

            sb.AppendLine("# Start of autogenerated actions using the recorder");

            foreach (var line in lines)
            {
                // Skip non-actions
                if (line.StartsWith("@@") ||
                    line.StartsWith("IMPORT") ||
                    line.StartsWith("@SENSITIVE") ||
                    line.StartsWith("#"))
                {
                    continue;
                }

                string fixedLine = line;

                // Fix action name
                if (fixedLine.StartsWith("System.LaunchApplication"))
                {
                    fixedLine = fixedLine.Replace(
                        "System.LaunchApplication",
                        "System.RunApplication.RunApplication"
                    );
                }

                // Add ProcessId
                if (fixedLine.StartsWith("System.RunApplication.RunApplication") &&
                    !fixedLine.Contains("ProcessId=>"))
                {
                    fixedLine += " ProcessId=> AppProcessId";
                }

                // Fix escaping
                fixedLine = fixedLine
                    .Replace("\\\\", "TEMP")
                    .Replace("\\", "\\\\")
                    .Replace("TEMP", "\\\\");

                // Add source
                sb.AppendLine("@@source: 'Recorder'");
                sb.AppendLine(fixedLine);
            }

            sb.AppendLine("# End of autogenerated actions using the recorder");

            return sb.ToString();
        }

        // ============================================================
        // 🔥 FORCE DOUBLE QUOTES
        // ============================================================
        private string WrapWithQuotes(string input)
        {
            return "\"" + input.Replace("\"", "\\\"") + "\"";
        }

        // ============================================================
        // PATCH
        // ============================================================
        private async Task SendPatch(Guid flowId, JsonObject payload)
        {
            var url = $"{_orgUrl}/api/data/v9.2/workflows({flowId})";

            var req = new HttpRequestMessage(new HttpMethod("PATCH"), url)
            {
                Content = new StringContent(
                    payload.ToJsonString(),
                    Encoding.UTF8,
                    "application/json")
            };

            var res = await _httpClient.SendAsync(req);
            var body = await res.Content.ReadAsStringAsync();

            Console.WriteLine($"PATCH {(int)res.StatusCode}");
            Console.WriteLine(body);

            if (!res.IsSuccessStatusCode)
                throw new Exception(body);
        }

        // ============================================================
        // ACTIVATE
        // ============================================================
        private async Task ActivateWorkflowAsync(Guid flowId)
        {
            var url = $"{_orgUrl}/api/data/v9.2/workflows({flowId})/Microsoft.Dynamics.CRM.ActivateWorkflow";

            var req = new HttpRequestMessage(HttpMethod.Post, url)
            {
                Content = new StringContent("{}", Encoding.UTF8, "application/json")
            };

            var res = await _httpClient.SendAsync(req);

            if (!res.IsSuccessStatusCode)
            {
                var body = await res.Content.ReadAsStringAsync();
                throw new Exception(body);
            }
        }
    }
}