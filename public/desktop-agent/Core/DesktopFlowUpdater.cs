using System;
using System.Linq;
using System.Net.Http;
using System.Text;
using System.Text.Json.Nodes;
using System.Threading.Tasks;

namespace WisprDesktopAgent.Core
{
    public class DesktopFlowUpdater
    {
        private readonly HttpClient _httpClient;
        private readonly string _orgUrl;

        // 🔥 TOGGLE THIS
        private readonly bool forceQuotes = true;

        public DesktopFlowUpdater(string orgUrl, string accessToken)
        {
            _orgUrl = orgUrl.TrimEnd('/');

            _httpClient = new HttpClient();

            _httpClient.DefaultRequestHeaders.Authorization =
                new System.Net.Http.Headers.AuthenticationHeaderValue("Bearer", accessToken);

            _httpClient.DefaultRequestHeaders.Add("OData-MaxVersion", "4.0");
            _httpClient.DefaultRequestHeaders.Add("OData-Version", "4.0");
            _httpClient.DefaultRequestHeaders.Add("Accept", "application/json");
        }

        // ============================================================
        // MAIN METHOD (WISPR → PAD → UPDATE)
        // ============================================================
        public async Task UpdateDesktopFlowAsync(Guid flowId, string wisprScript)
        {
            if (string.IsNullOrWhiteSpace(wisprScript))
                throw new ArgumentException("Script cannot be empty");

            var padScript = ConvertWisprToPad(wisprScript);

            // 🔥 Apply quote mode if needed
            var finalDefinition = forceQuotes
                ? WrapWithQuotes(padScript)
                : padScript;

            await UpdateInternal(flowId, finalDefinition);

            Console.WriteLine("✅ Flow updated");
        }

        // ============================================================
        // STATIC TEST
        // ============================================================
